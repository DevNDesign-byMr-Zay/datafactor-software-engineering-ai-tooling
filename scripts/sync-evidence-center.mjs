import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const canonicalFile = new URL('../apps/aetherforge-workbench/evidence-center.js', import.meta.url);
const moduleFile = new URL('../apps/aetherforge-commercial/evidence-center.js', import.meta.url);
const browserFile = new URL('../apps/aetherforge-commercial/evidence-center.browser.js', import.meta.url);

const browserHeader =
  '// Generated from apps/aetherforge-workbench/evidence-center.js by scripts/sync-evidence-center.mjs; do not edit directly.\n';

const moduleWrapper =
  '// Canonical Evidence Center logic and presentation live in the companion workbench.\n' +
  '// The commercial classic-browser artifact is generated by scripts/sync-evidence-center.mjs.\n' +
  "export { classifyEvidence, normalizeEvidenceDocument, readEvidenceFile, nextEvidenceTab, exportEvidenceVerdict } from '../aetherforge-workbench/evidence-center.js';\n";

const receiptBody =
  "    const body=JSON.stringify({action:'receipt',inputs:{receipt,receiptFingerprint:current,...(previous?{previousFingerprint:previous}:{})}});";

const offlineGuard = [
  "    if (location.protocol === 'file:') {",
  "      rejectLocally('Maintained fingerprint verification requires the localhost adapter. Start with START-AETHERFORGE.cmd; offline data is not a verified receipt.', receipt, current, previous);",
  '      return;',
  '    }',
].join('\n');

function assert(ok, message) {
  if (!ok) throw new Error(`Evidence Center generator: ${message}`);
}

export function generateEvidenceCenterArtifacts(canonical) {
  assert(typeof canonical === 'string' && canonical.length > 0, 'empty canonical source');
  assert(canonical.includes(receiptBody), 'expected maintained receipt request changed');
  assert(
    canonical.split(receiptBody).length === 2,
    'expected exactly one maintained receipt request',
  );
  assert(
    !canonical.includes("if (location.protocol === 'file:')"),
    'commercial-only file protection must not leak into companion source',
  );

  const exports = [...canonical.matchAll(/^export (?:async )?function ([A-Za-z][A-Za-z0-9]*)/gmu)]
    .map((match) => match[1])
    .sort();
  assert(
    JSON.stringify(exports) ===
      JSON.stringify(
        [
          'classifyEvidence',
          'exportEvidenceVerdict',
          'nextEvidenceTab',
          'normalizeEvidenceDocument',
          'readEvidenceFile',
        ].sort(),
      ),
    'canonical public function exports changed',
  );

  const browserScript = canonical
    .replace(/^export (async )?function /gmu, (_, asyncKeyword = '') => `${asyncKeyword}function `)
    .replace(receiptBody, `${offlineGuard}\n${receiptBody}`);

  return {
    module: moduleWrapper,
    browser: browserHeader + browserScript,
  };
}

export async function syncEvidenceCenter({ write = false } = {}) {
  const canonical = await readFile(canonicalFile, 'utf8');
  const generated = generateEvidenceCenterArtifacts(canonical);
  const outputs = [
    [moduleFile, generated.module],
    [browserFile, generated.browser],
  ];
  for (const [path, expected] of outputs) {
    if (write) {
      await writeFile(path, expected, 'utf8');
    } else {
      const actual = await readFile(path, 'utf8');
      assert(actual === expected, `generated file out of sync: ${path.pathname}`);
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2] ?? '--check';
  if (!['--check', '--write'].includes(mode) || process.argv.length > 3) {
    console.error('Usage: node scripts/sync-evidence-center.mjs [--check|--write]');
    process.exitCode = 2;
  } else {
    syncEvidenceCenter({ write: mode === '--write' }).catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
  }
}
